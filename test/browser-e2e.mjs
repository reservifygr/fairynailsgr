import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
mkdirSync('artifacts',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const errors=[];
const desktop=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
desktop.on('pageerror',err=>errors.push(err.message));
const base='http://127.0.0.1:8123/';
await desktop.goto(base+'index.html',{waitUntil:'domcontentloaded'});
await desktop.waitForSelector('.hero h1');
await desktop.waitForTimeout(1500);
assert.match(await desktop.locator('.hero h1').innerText(),/στιγμές/i);
await desktop.screenshot({path:'artifacts/home-desktop.png',fullPage:true});
await desktop.locator('#langToggle').click();
await desktop.waitForLoadState('domcontentloaded');
await desktop.waitForSelector('.hero h1');
assert.match(await desktop.locator('.hero h1').innerText(),/best moments/i);
await desktop.goto(base+'services.html',{waitUntil:'domcontentloaded'});
assert.equal(await desktop.locator('.service-card').count(),8);
await desktop.locator('[data-filter="pedicure"]').click();
assert.equal(await desktop.locator('.service-card').count(),2);
await desktop.goto(base+'booking.html',{waitUntil:'domcontentloaded'});
await desktop.locator('[data-time]').first().click();
await desktop.locator('#name').fill('Demo Test');
await desktop.locator('#phone').fill('6900000000');
await desktop.locator('#consent').check();
await desktop.locator('#bookForm button[type="submit"]').click();
await desktop.waitForSelector('#bookingSuccess:not([hidden])');
assert.match(await desktop.locator('#bookingSuccess').innerText(),/demo booking/i);
await desktop.goto(base+'admin.html',{waitUntil:'domcontentloaded'});
await desktop.waitForSelector('#adminBody');
assert.match(await desktop.locator('#adminBody').innerText(),/Demo Test/);
await desktop.screenshot({path:'artifacts/admin-desktop.png',fullPage:true});
await desktop.locator('[data-remove]').first().click();
assert.match(await desktop.locator('#adminBody').innerText(),/No demo appointments/);
const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
mobile.on('pageerror',err=>errors.push(err.message));
await mobile.goto(base+'index.html',{waitUntil:'domcontentloaded'});
await mobile.waitForSelector('.hero h1');
await mobile.waitForTimeout(1500);
await mobile.screenshot({path:'artifacts/home-mobile.png',fullPage:true});
await mobile.locator('#mobileToggle').click();
assert.equal(await mobile.locator('#mobileMenu').evaluate(e=>getComputedStyle(e).display),'flex');
const bodyWidth=await mobile.evaluate(()=>document.documentElement.scrollWidth);
assert.ok(bodyWidth<=392,'Mobile overflow: '+bodyWidth);
await mobile.goto(base+'booking.html',{waitUntil:'domcontentloaded'});
await mobile.screenshot({path:'artifacts/booking-mobile.png',fullPage:true});
assert.equal(errors.length,0,'Browser errors: '+errors.join('; '));
console.log('PASS: desktop, mobile, translation, services, booking, staff demo, cancellations, no JS exceptions');
await browser.close();
